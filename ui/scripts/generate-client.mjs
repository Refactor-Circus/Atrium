// Generates the SDK's typed client of Atrium's own API (AC 74) from the
// repository's committed openapi.json (`composer openapi:export`):
//
//   pnpm -C ui generate:client            write ui/sdk/src/client/schema.d.ts
//   pnpm -C ui generate:client --check    fail when the file is not what it would write
//
// The file's first line is `// openapi.json sha256: <hex>`, the SHA-256 of
// openapi.json with LF line endings, so the PHP suite
// (tests/Feature/OpenApiTest.php, which runs without Node) can tell whether
// the client was generated from the committed document. `composer test:ui`
// runs the check.
//
// openapi-typescript is a pinned dev dependency of the SDK, so it is
// resolved from ui/sdk. Schemas with no listed properties (the JSON
// objects keyed by name: settings, data, theme properties) become
// `Record<string, unknown>`.

import { createHash } from 'node:crypto'
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { createRequire } from 'node:module'
import { dirname, join, relative } from 'node:path'
import { fileURLToPath, pathToFileURL } from 'node:url'

const repository = fileURLToPath(new URL('../../', import.meta.url))
const layer = join(repository, 'ui', 'sdk')
const source = join(repository, 'openapi.json')
const target = join(layer, 'src', 'client', 'schema.d.ts')
const check = process.argv.includes('--check')

const REGENERATE = 'run `composer openapi:export`, then `pnpm -C ui generate:client`, and commit openapi.json and ui/sdk/src/client/schema.d.ts'

function fail(message) {
  console.error(`[generate:client] ${message}`)
  process.exit(1)
}

if (!existsSync(source)) {
  fail(`${source} is missing: ${REGENERATE}.`)
}

const document = readFileSync(source, 'utf8').replace(/\r\n/g, '\n')
const sha = createHash('sha256').update(document, 'utf8').digest('hex')

const require = createRequire(join(layer, 'package.json'))
const generator = join(dirname(require.resolve('openapi-typescript/package.json')), 'dist', 'index.mjs')
const { default: openapiTS, astToString } = await import(pathToFileURL(generator).href)

const ast = await openapiTS(JSON.parse(document), { emptyObjectsUnknown: true })

const generated = [
  `// openapi.json sha256: ${sha}`,
  '// Generated by `pnpm -C ui generate:client` from openapi.json with openapi-typescript. Do not edit.',
  '',
  astToString(ast)
].join('\n')

const name = relative(repository, target)

if (check) {
  const current = existsSync(target) ? readFileSync(target, 'utf8') : null

  if (current !== generated) {
    fail(`${name} is out of date with openapi.json: ${REGENERATE}.`)
  }

  console.log(`[generate:client] ${name} is current (${sha}).`)
  process.exit(0)
}

mkdirSync(dirname(target), { recursive: true })
writeFileSync(target, generated)

console.log(`[generate:client] ${name}: ${sha}`)
