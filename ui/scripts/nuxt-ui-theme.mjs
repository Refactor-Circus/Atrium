// Writes ui/sdk/css/nuxt-ui-theme.css: the Tailwind theme Nuxt UI's Vite
// plugin generates (`#build/ui.css`, less its `@source`), with Nuxt UI's
// `light`/`dark` variants, for module stylesheets (D-084). A module's build
// does not run Nuxt UI's plugin, so it reads the theme from here.
//
//   node scripts/nuxt-ui-theme.mjs           write it
//   node scripts/nuxt-ui-theme.mjs --check   fail when it is out of date
import { readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'
import { fileURLToPath, pathToFileURL } from 'node:url'

const sdk = fileURLToPath(new URL('../sdk/', import.meta.url))
const ui = join(sdk, 'node_modules/@nuxt/ui')
const shared = join(ui, 'dist/shared')
const chunk = readdirSync(shared).find(name => name.startsWith('ui.') && name.endsWith('.mjs'))
const { d: defaults, r: resolveColors, a: defaultUiConfig, g: templates } = await import(pathToFileURL(join(shared, chunk)).href)
const { atriumUiConfig } = await import(pathToFileURL(join(sdk, 'vite/ui-config.mjs')).href)

const options = { ...defaults, theme: { ...defaults.theme, colors: resolveColors(defaults.theme?.colors) } }
const template = templates(options, { ...defaultUiConfig(options.theme.colors), ...atriumUiConfig }).find(t => t.filename === 'ui.css')
const generated = (await template.getContents({})).replace(/^@source[^\n]*\n+/m, '')
const { version } = JSON.parse(readFileSync(join(ui, 'package.json'), 'utf8'))

const css = `/*
 * Nuxt UI ${version}'s Tailwind theme, as its Vite plugin generates it for
 * Atrium's build: the colour scales, radii and the semantic text, background,
 * border and ring colours (text-muted, bg-elevated, ...), and its light and
 * dark variants. Generated by ui/scripts/nuxt-ui-theme.mjs; do not edit.
 */
@custom-variant light (&:where(.light, .light *));
@custom-variant dark (&:where(.dark, .dark *));

${generated.trim()}
`

const target = join(sdk, 'css/nuxt-ui-theme.css')

if (process.argv.includes('--check')) {
  if (readFileSync(target, 'utf8') !== css) {
    console.error('[nuxt-ui-theme] ui/sdk/css/nuxt-ui-theme.css is out of date: run `node scripts/nuxt-ui-theme.mjs`.')
    process.exit(1)
  }
} else {
  writeFileSync(target, css)
}
